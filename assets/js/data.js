  function isValidAnswers(answers) {
    if (!Array.isArray(answers) || answers.length !== 30) {
      return false;
    }
    return answers.every(function (v) {
      return Number.isInteger(v) && v >= 0 && v <= 4;
    });
  }

  function parseAnswerString(queryValue) {
    if (typeof queryValue !== "string" || !/^[0-4]{30}$/.test(queryValue)) {
      return null;
    }
    return queryValue.split("").map(function (ch) {
      return Number(ch);
    });
  }

  function encodeAnswerString(answers) {
    if (!isValidAnswers(answers)) {
      throw new Error("유효한 30문항 응답 배열(각 0~4 정수)이 필요합니다.");
    }
    return answers.join("");
  }

  function scoreByType(answers) {
    if (!isValidAnswers(answers)) {
      throw new Error("유효한 30문항 응답 배열(각 0~4 정수)이 필요합니다.");
    }
    return TYPES.map(function (type) {
      const score = type.items.reduce(function (sum, itemNumber) {
        return sum + answers[itemNumber - 1];
      }, 0);
      return {
        id: type.id,
        symbol: type.symbol,
        key: type.key,
        name: type.name,
        desc: type.desc,
        items: type.items.slice(),
        score: score,
        level: level(score, "type")
      };
    });
  }

  function totalScore(answers) {
    if (!isValidAnswers(answers)) {
      throw new Error("유효한 30문항 응답 배열(각 0~4 정수)이 필요합니다.");
    }
    return answers.reduce(function (sum, value) {
      return sum + value;
    }, 0);
  }

  function level(score, kind) {
    const mode = kind || "total";
    if (typeof score !== "number" || Number.isNaN(score)) {
      throw new Error("점수는 숫자여야 합니다.");
    }
    const table = mode === "type" ? TYPE_LEVELS : TOTAL_LEVELS;
    const maxAllowed = mode === "type" ? 12 : 120;
    if (!Number.isInteger(score) || score < 0 || score > maxAllowed) {
      throw new RangeError("허용 범위를 벗어난 점수입니다: " + score);
    }
    for (let i = 0; i < table.length; i += 1) {
      const row = table[i];
      if (score >= row.min && score <= row.max) {
        return Object.assign({}, row);
      }
    }
    throw new RangeError("등급을 찾을 수 없는 점수입니다: " + score);
  }

